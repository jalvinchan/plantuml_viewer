import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

const samples = [
  { id: 'welcome', file: 'samples/welcome.md', label: '🌟 Welcome & Overview' },
  { id: 'sequence', file: 'samples/oauth2.md', label: '🔀 Sequence: OAuth 2.0 PKCE' },
  { id: 'architecture', file: 'samples/architecture.md', label: '🏗️ Architecture: Cloud Microservices' },
  { id: 'mindmap', file: 'samples/mindmap.md', label: '🧠 Mindmap: Software Architecture' },
  { id: 'activity', file: 'samples/activity.md', label: '⚡ Activity: Order Processing Flow' },
  { id: 'state', file: 'samples/state.md', label: '🔄 State: Connection Lifecycle' }
];

const catalog = samples.map(sample => ({
  ...sample,
  content: fs.readFileSync(path.join(root, sample.file), 'utf8')
}));

const output = `/* eslint-disable */
// Generated by scripts/build-sample-catalog.mjs.
// Edit the Markdown files in samples/, then run npm run samples:sync.
(function (global) {
  'use strict';

  global.StudioSamples = ${JSON.stringify(catalog, null, 2)};
})(typeof window !== 'undefined' ? window : globalThis);
`;

fs.writeFileSync(path.join(root, 'js/samples.js'), output);
